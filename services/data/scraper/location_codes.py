def get_location_code(location_name: str) -> Optional[str]:
    """
    장소 이름으로 코드 조회

    Args:
        location_name: 장소 이름 (예: "익산", "양구")

    Returns:
        장소 코드 (예: "IK", "YG") 또는 None
    """
    # 정확한 매칭
    if location_name in LOCATION_CODES:
        return LOCATION_CODES[location_name]

    # 부분 매칭 (예: "익산시" → "익산")
    for name, code in LOCATION_CODES.items():
        if name in location_name or location_name in name:
            return code

    return None


def get_location_name(location_code: str) -> Optional[str]:
    """
    코드로 장소 이름 조회

    Args:
        location_code: 장소 코드 (예: "IK", "YG")

    Returns:
        장소 이름 (예: "익산", "양구") 또는 None
    """
    return LOCATION_NAMES.get(location_code.upper())


def normalize_location(location_input: str) -> Tuple[Optional[str], Optional[str]]:
    """
    장소 입력을 정규화하여 (코드, 이름) 반환

    Args:
        location_input: 장소 이름 또는 코드

    Returns:
        (코드, 이름) 튜플. 찾지 못하면 (None, None)
    """
    # 코드로 먼저 시도
    if location_input.upper() in LOCATION_NAMES:
        code = location_input.upper()
        return (code, LOCATION_NAMES[code])

    # 이름으로 시도
    code = get_location_code(location_input)
    if code:
        return (code, LOCATION_NAMES.get(code, location_input))

    return (None, None)


