KO_EN_MAP = {k: v["en"] for k, v in TRANSLATIONS.items()}


def make_auto_translator(lang: str):
    """Create a translation function for Jinja2 global registration."""
    def _t(text: str) -> str:
        if lang == 'ko' or not text:
            return text
        entry = TRANSLATIONS.get(text)
        if entry:
            return entry.get(lang, entry.get('en', text))
        return text  # fallback: return Korean as-is
    return _t


def get_js_translations(lang: str) -> dict:
    """Return translation dictionary for JavaScript use."""
    if lang == 'ko':
        return {}
    result = {}
    for ko_text, translations in TRANSLATIONS.items():
        result[ko_text] = translations.get(lang, translations.get('en', ko_text))
    return result
